#!/usr/bin/env python3
"""Bundle n8n Code-node sources into importable workflow JSON.

Templates in n8n/workflows/src/*.json reference code as
    "jsCode": "@@code:<file>.js"        (relative to n8n/code/nodes/)
Each node file may require('../lib/<name>') helpers from n8n/code/lib/; they are
inlined (with their own dependencies) as tiny CommonJS modules, so exactly the
same files run under `node --test` and inside n8n.

Usage:  build-workflows.py           write n8n/workflows/*.json
        build-workflows.py --check   exit 1 if any generated file is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CODE = ROOT / "n8n" / "code"
SRC = ROOT / "n8n" / "workflows" / "src"
OUT = ROOT / "n8n" / "workflows"
MARKER = "@@code:"
REQUIRE_RE = re.compile(r"""require\(\s*['"](\.{1,2}/[^'"]+)['"]\s*\)""")

PRELUDE = """// Generated by scripts/build-workflows.py from n8n/code/ - edit those files, not this node.
const __libs = {};
const __require = (spec) => {
  const name = spec.split('/').pop().replace(/\\.js$/, '');
  if (Object.prototype.hasOwnProperty.call(__libs, name)) return __libs[name];
  return require(spec);
};
"""


def _lib_name(spec: str) -> str:
    return Path(spec).name.removesuffix(".js")


def _collect(source: str, order: list[str], visiting: set[str]) -> None:
    """Append required lib names to `order`, dependencies first."""
    for spec in REQUIRE_RE.findall(source):
        name = _lib_name(spec)
        if name in order:
            continue
        if name in visiting:
            raise SystemExit(f"circular require involving {name}")
        path = CODE / "lib" / f"{name}.js"
        if not path.exists():
            raise SystemExit(f"unknown lib in require('{spec}')")
        visiting.add(name)
        _collect(path.read_text(), order, visiting)
        visiting.discard(name)
        order.append(name)


def bundle(node_file: str) -> str:
    path = CODE / "nodes" / node_file
    if not path.exists():
        raise SystemExit(f"missing node source: {path.relative_to(ROOT)}")
    entry = path.read_text()
    order: list[str] = []
    _collect(entry, order, set())
    parts = [PRELUDE]
    for name in order:
        source = (CODE / "lib" / f"{name}.js").read_text()
        parts.append(
            f"__libs[{json.dumps(name)}] = (function (require) {{\n"
            "  const module = { exports: {} };\n"
            "  const exports = module.exports;\n"
            f"{source}\n"
            "  return module.exports;\n"
            "})(__require);\n"
        )
    parts.append(f"return (async function (require) {{\n{entry}\n}}).call(this, __require);\n")
    return "".join(parts)


def _render(value):
    if isinstance(value, dict):
        return {key: _render(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_render(item) for item in value]
    if isinstance(value, str) and value.startswith(MARKER):
        return bundle(value[len(MARKER):])
    return value


def build_all() -> dict[Path, str]:
    outputs = {}
    for path in sorted(SRC.glob("*.json")):
        workflow = _render(json.loads(path.read_text()))
        outputs[OUT / path.name] = json.dumps(workflow, indent=2, ensure_ascii=False) + "\n"
    return outputs


def main(argv: list[str]) -> int:
    outputs = build_all()
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run scripts/build-workflows.py)")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
