#!/usr/bin/env bash
# Discover default-VPC networking and the operator's public IP, build the Lambda
# bundle, then deploy the stack. Re-runnable; this is the ONLY way the operator IP
# allowed on RDS is changed (it lives in the template as operatorCidr).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
REGION="${AWS_REGION:-ap-south-1}"
STAGE="${STAGE:-dev}"
STACK="loan-eligibility-engine-$STAGE"

VPC_ID="$(aws ec2 describe-vpcs --region "$REGION" --filters Name=is-default,Values=true \
  --query 'Vpcs[0].VpcId' --output text)"
if [[ -z "$VPC_ID" || "$VPC_ID" == "None" ]]; then
  echo "No default VPC in $REGION. Create one with: aws ec2 create-default-vpc --region $REGION" >&2
  exit 1
fi
SUBNETS="$(aws ec2 describe-subnets --region "$REGION" \
  --filters Name=vpc-id,Values="$VPC_ID" Name=default-for-az,Values=true \
  --query 'Subnets[].SubnetId' --output text)"
ROUTE_TABLES="$(aws ec2 describe-route-tables --region "$REGION" \
  --filters Name=vpc-id,Values="$VPC_ID" --query 'RouteTables[].RouteTableId' --output text)"
# An S3 gateway endpoint created by someone else (not this stack) must not be duplicated.
# This stack's own endpoint is identified by its physical ID (VPC endpoints may not carry
# CloudFormation system tags), so redeploys keep it instead of flip-flopping.
OWN_ENDPOINT="$(aws cloudformation describe-stack-resource --region "$REGION" --stack-name "$STACK" \
  --logical-resource-id S3GatewayEndpoint --query StackResourceDetail.PhysicalResourceId --output text 2>/dev/null || echo none)"
FOREIGN_S3_ENDPOINTS="$(aws ec2 describe-vpc-endpoints --region "$REGION" \
  --filters Name=vpc-id,Values="$VPC_ID" Name=service-name,Values="com.amazonaws.$REGION.s3" \
            Name=vpc-endpoint-type,Values=Gateway \
  --query "length(VpcEndpoints[?VpcEndpointId!='$OWN_ENDPOINT' && State!='deleted' && State!='deleting'])" \
  --output text)"
MY_IP="$(curl -fsS https://checkip.amazonaws.com | tr -d '[:space:]')"

{
  echo "# Generated by scripts/deploy.sh — do not edit or commit."
  echo "vpcId: $VPC_ID"
  echo "subnetIds:"; for s in $SUBNETS; do echo "  - $s"; done
  echo "routeTableIds:"; for r in $ROUTE_TABLES; do echo "  - $r"; done
  echo "createS3Endpoint: '$([[ "$FOREIGN_S3_ENDPOINTS" == "0" ]] && echo true || echo false)'"
  echo "operatorCidr: $MY_IP/32"
} > config/aws.generated.yml
cat config/aws.generated.yml

scripts/build-lambda.sh
npx serverless deploy --stage "$STAGE" --region "$REGION" --verbose
